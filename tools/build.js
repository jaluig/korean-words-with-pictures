#!/usr/bin/env node
/*
 * Build helper (no npm deps):
 *   node tools/build.js            -> download missing emoji images, write js/emoji-ok.js, update index.html data tags, validate data
 *   node tools/build.js --check    -> validate only (no downloads)
 *
 * Emoji images come from Microsoft Fluent Emoji (MIT) 3D set, converted to WebP (needs curl + ImageMagick `convert`).
 */
const fs = require('fs'); const path = require('path'); const vm = require('vm'); const { execFileSync } = require('child_process');
const ROOT = path.join(__dirname, '..');
const Scene = require(path.join(ROOT, 'js/scene.js'));
const CHECK = process.argv.includes('--check');

// UI emoji used directly by the app code
const UI = ['📚', '🏆', '🎉', '🖼️', '💬', '🎧', '🧩', '🃏', '⌨️', '⚡', '👍', '💪', '❌', '🧱', '👣', '🌱', '🌿', '🌳', '🏅', '👑', '🔥', '⭐', '🌟', '💎', '🎓', '🧠', '🥇', '🗂️', '📖', '💯'];

const dataFiles = fs.readdirSync(path.join(ROOT, 'data')).filter((f) => f.endsWith('.js')).sort();
const ctx = { WORDS: [], STORIES: [] }; vm.createContext(ctx);
for (const f of dataFiles) vm.runInContext(fs.readFileSync(path.join(ROOT, 'data', f), 'utf8'), ctx, { filename: f });
const WORDS = ctx.WORDS; const STORIES = ctx.STORIES;

const problems = []; const warn = (m) => problems.push(m);
const dict = new Map();
for (const w of WORDS) {
  if (!w.w || !w.pic) warn(`missing fields: ${JSON.stringify(w).slice(0, 80)}`);
  if (dict.has(w.w)) warn(`duplicate word: ${w.w}`);
  dict.set(w.w, w);
  if (!w.ex || !w.ex.length) warn(`no example: ${w.w}`);
  else if (!w.ex.some((s) => s.includes(`|${w.w}}`) || s.includes(`{${w.w}}`))) warn(`word not tagged in its own sentences: ${w.w}`);
  for (const s of w.ex || []) {
    if ((s.match(/\{/g) || []).length !== (s.match(/\}/g) || []).length) warn(`unbalanced braces: ${w.w}: ${s}`);
  }
  try { Scene.parse(w.pic); } catch (e) { warn(`bad scene ${w.w}: ${e.message}`); }
}

// lemmas referenced in sentences but not (yet) in the dictionary -> ideas for next words
const missing = new Map();
const scan = (s) => String(s).replace(/\{([^}|]+)(?:\|([^}]+))?\}/g, (m, f, l) => { const k = l || f; if (!dict.has(k)) missing.set(k, (missing.get(k) || 0) + 1); return m; });
WORDS.forEach((w) => (w.ex || []).forEach(scan));
STORIES.forEach((st) => st.p.forEach((p) => scan(p.s)));

// emoji set
const need = new Set(UI);
WORDS.forEach((w) => Scene.emojis(w.pic).forEach((e) => need.add(e)));
STORIES.forEach((st) => { Scene.emojis(st.cover || '').forEach((e) => need.add(e)); st.p.forEach((p) => Scene.emojis(p.pic).forEach((e) => need.add(e))); });

const idx = JSON.parse(fs.readFileSync(path.join(__dirname, 'fluent_index.json'), 'utf8'));
const outDir = path.join(ROOT, 'img/e'); fs.mkdirSync(outDir, { recursive: true });
const tmp = fs.mkdtempSync(path.join(require('os').tmpdir(), 'emo-'));
const noImage = [];
let downloaded = 0;
for (const e of need) {
  const code = Scene.code(e);
  const dst = path.join(outDir, `${code}.webp`);
  if (fs.existsSync(dst)) continue;
  let ent = idx[code] || idx[code.replace(/-fe0f/g, '')];
  if (!ent) { noImage.push(`${e} (${code})`); continue; }
  if (CHECK) continue;
  const url = `https://raw.githubusercontent.com/microsoft/fluentui-emoji/main/${ent.path.split('/').map(encodeURIComponent).join('/')}`;
  const png = path.join(tmp, `${code}.png`);
  try {
    execFileSync('curl', ['-sSfL', '--retry', '3', '-o', png, url]);
    execFileSync('convert', [png, '-quality', '82', '-define', 'webp:method=6', dst]);
    downloaded++;
  } catch (err) { noImage.push(`${e} (${code}) download failed`); }
}
fs.rmSync(tmp, { recursive: true, force: true });

// available list
const have = fs.readdirSync(outDir).filter((f) => f.endsWith('.webp')).map((f) => f.replace('.webp', '')).sort();
fs.writeFileSync(path.join(ROOT, 'js/emoji-ok.js'), `/* generated by tools/build.js */\nwindow.EMOJI_OK = new Set(${JSON.stringify(have)});\n`);

// index.html data tags
const htmlPath = path.join(ROOT, 'index.html');
let html = fs.readFileSync(htmlPath, 'utf8');
const tags = dataFiles.map((f) => `<script src="data/${f}"></script>`).join('\n');
html = html.replace(/<!-- DATA -->[\s\S]*?<!-- \/DATA -->/, `<!-- DATA -->\n${tags}\n<!-- /DATA -->`);
fs.writeFileSync(htmlPath, html);

// report
const byLevel = {}; WORDS.forEach((w) => { byLevel[w.l || 1] = (byLevel[w.l || 1] || 0) + 1; });
const byCat = {}; WORDS.forEach((w) => { byCat[w.c] = (byCat[w.c] || 0) + 1; });
console.log(`words: ${WORDS.length}  stories: ${STORIES.length}  emoji used: ${need.size}  images: ${have.length} (+${downloaded} new)`);
console.log('levels:', JSON.stringify(byLevel));
console.log('cats:', JSON.stringify(byCat));
if (noImage.length) console.log(`no Fluent image (text fallback): ${noImage.join(', ')}`);
if (problems.length) console.log(`\nPROBLEMS (${problems.length}):\n  ${problems.join('\n  ')}`);
const top = [...missing.entries()].sort((a, b) => b[1] - a[1]);
if (process.argv.includes('--missing')) console.log(`\nlemmas used in sentences but not in dictionary (${top.length}):\n  ${top.map(([k, n]) => `${k}:${n}`).join(' ')}`);
else console.log(`\n${top.length} sentence lemmas not yet in dictionary (run with --missing to list)`);
